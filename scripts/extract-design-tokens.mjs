#!/usr/bin/env node
/**
 * Extract the pane's implementation tokens from the approved Design handoff.
 *
 * The handoff uses the same `--havemind-*` CSS custom properties as the
 * plugin. Keeping this small generated manifest gives tests a stable contract:
 * a spacing change in the mockup cannot quietly drift away from styles.css.
 *
 * Usage:
 *   node scripts/extract-design-tokens.mjs            # write tokens.json
 *   node scripts/extract-design-tokens.mjs --check    # fail if stale (CI)
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const DESIGN = fileURLToPath(
  new URL('../design/minimal-pane/handoff.html', import.meta.url),
);
const OUT = fileURLToPath(
  new URL('../design/minimal-pane/tokens.json', import.meta.url),
);

const TOKENS = [
  ['tab-height', '--havemind-tab-height', 'height'],
  ['tab-height-touch', '--havemind-tab-height-touch', 'height'],
  ['tab-label-size', '--havemind-tab-label-size', 'font-size'],
  ['tab-label-weight', '--havemind-tab-label-weight', 'font-weight'],
  ['tab-active-weight', '--havemind-tab-active-weight', 'font-weight'],
  ['tab-active-rule', '--havemind-tab-active-rule', 'border-bottom'],
  ['tab-gap', '--havemind-tab-gap', 'gap'],
  ['tabs-pad', '--havemind-tabs-pad', 'padding'],
  ['hero-pad', '--havemind-hero-pad', 'padding'],
  ['hero-gap', '--havemind-hero-gap', 'gap'],
  ['hero-flower-gap', '--havemind-hero-flower-gap', 'margin-bottom'],
  ['hero-title-size', '--havemind-hero-title-size', 'font-size'],
  ['hero-title-weight', '--havemind-hero-title-weight', 'font-weight'],
  ['hero-sub-size', '--havemind-hero-sub-size', 'font-size'],
  ['flower-max', '--havemind-flower-max', 'max-width'],
  ['status-size', '--havemind-status-size', 'font-size'],
  ['status-weight', '--havemind-status-weight', 'font-weight'],
  ['status-gap', '--havemind-status-gap', 'gap'],
  ['status-dot-size', '--havemind-status-dot-size', 'width'],
  ['status-detail-indent', '--havemind-status-detail-indent', 'padding-left'],
  ['status-detail-size', '--havemind-status-detail-size', 'font-size'],
  ['status-detail-gap', '--havemind-status-detail-gap', 'margin-top'],
  ['body-pad', '--havemind-body-pad', 'padding'],
  ['roster-row-height', '--havemind-roster-row-height', 'min-height'],
  ['activity-row-pad', '--havemind-activity-row-pad', 'padding'],
  ['row-time-size', '--havemind-row-time-size', 'font-size'],
  ['dot-size', '--havemind-dot-size', 'width'],
];

function readCustomProperty(html, property) {
  const escaped = property.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const match = html.match(new RegExp(`${escaped}:\\s*([^;]+);`));
  if (!match?.[1]) {
    throw new Error(`Design handoff does not declare ${property}`);
  }
  return match[1].trim();
}

function extract() {
  const html = readFileSync(DESIGN, 'utf8');
  const tokens = Object.fromEntries(
    TOKENS.map(([name, css, property]) => [
      name,
      { value: readCustomProperty(html, css), property, occurrences: 1, css },
    ]),
  );

  return {
    $comment:
      'GENERATED by scripts/extract-design-tokens.mjs from the approved minimal-pane handoff (plan 010). Do not edit by hand.',
    source: 'design/minimal-pane/handoff.html',
    tokens,
  };
}

const result = extract();
const serialised = `${JSON.stringify(result, null, 2)}\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    console.error('tokens.json is missing, run: node scripts/extract-design-tokens.mjs');
    process.exit(1);
  }
  if (current !== serialised) {
    console.error('tokens.json is stale against the design handoff.\nRun: node scripts/extract-design-tokens.mjs');
    process.exit(1);
  }
  console.log(`PASS: tokens.json matches the design (${Object.keys(result.tokens).length} tokens)`);
} else {
  writeFileSync(OUT, serialised);
  console.log(`Wrote ${OUT} (${Object.keys(result.tokens).length} tokens)`);
}
